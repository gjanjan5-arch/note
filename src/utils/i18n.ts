const INSTALLED_LANGS_KEY = 'tindahan_installed_languages';
const ACTIVE_LANG_KEY = 'tindahan_active_language';

export function getInstalledLanguages(): LanguageCode[] {
  try {
    const raw = localStorage.getItem(INSTALLED_LANGS_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.includes('en')) {
        return parsed;
      }
    }
  } catch (e) {
    // fallback
  }
  // English is installed by default
  const defaultList: LanguageCode[] = ['en'];
  localStorage.setItem(INSTALLED_LANGS_KEY, JSON.stringify(defaultList));
  return defaultList;
}

export function saveInstalledLanguages(langs: LanguageCode[]) {
  const safeLangs = Array.from(new Set(['en', ...langs]));
  localStorage.setItem(INSTALLED_LANGS_KEY, JSON.stringify(safeLangs));
}

export function getActiveLanguage(): LanguageCode {
  try {
    const raw = localStorage.getItem(ACTIVE_LANG_KEY) as LanguageCode | null;
    if (raw && ['en', 'tl', 'ja', 'zh', 'ko'].includes(raw)) {
      const installed = getInstalledLanguages();
      if (installed.includes(raw)) {
        return raw;
      }
    }
  } catch (e) {
    // fallback
  }
  // Default is ALWAYS English
  localStorage.setItem(ACTIVE_LANG_KEY, 'en');
  return 'en';
}

export function setActiveLanguageStorage(lang: LanguageCode) {
  localStorage.setItem(ACTIVE_LANG_KEY, lang);
}

export function translate(lang: LanguageCode, key: string, params?: Record<string, string | number>): string {
  if (!key) return '';
  const langDict = translations[lang] || translations.en;
  const normalizedKey = key.trim();
  const lowerKey = normalizedKey.toLowerCase();

  // 1. Direct match
  let text = langDict[normalizedKey] || langDict[lowerKey];

  // 2. Fallback to English
  if (!text && translations.en) {
    text = translations.en[normalizedKey] || translations.en[lowerKey];
  }

  // 3. Fallback for case-insensitive matches in en dictionary
  if (!text && translations.en) {
    const enKey = Object.keys(translations.en).find((k) => k.toLowerCase() === lowerKey);
    if (enKey) {
      text = (translations[lang] && translations[lang][enKey]) || translations.en[enKey];
    }
  }

  // 4. Safe humanized fallback: never show raw internal developer keys (e.g. search_placeholder, btn_add_item, PAUTANG_COLLECTIBLES)
  if (!text) {
    if (lowerKey === 'pautang_collectibles' || lowerKey === 'pautang_collectible') {
      text = 'Pautang Collectible';
    } else if (lowerKey.startsWith('btn_') || lowerKey.startsWith('button_')) {
      const clean = lowerKey.replace(/^button_|^btn_/, '').replace(/_/g, ' ');
      text = clean.charAt(0).toUpperCase() + clean.slice(1);
    } else if (lowerKey.startsWith('nav_')) {
      const clean = lowerKey.replace(/^nav_/, '').replace(/_/g, ' ');
      text = clean.charAt(0).toUpperCase() + clean.slice(1);
    } else if (lowerKey.startsWith('search_')) {
      text = 'Search...';
    } else if (lowerKey.includes('_')) {
      const clean = lowerKey.replace(/_/g, ' ');
      text = clean.charAt(0).toUpperCase() + clean.slice(1);
    } else {
      text = key;
    }
  }

  if (params) {
    Object.entries(params).forEach(([paramKey, val]) => {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(val));
    });
  }

  return text;
}
